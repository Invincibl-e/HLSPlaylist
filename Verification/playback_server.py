#!/usr/bin/env python3
"""Test-only origin/proxy. Device connects via an SSH reverse tunnel.

All rewritten manifests are generated by the compiled local HLSPlaylist Probe.
Creates AES-128, byte-range and sliding live fixtures from Apple's public media.
"""
import http.server
import base64
import json
import pathlib
import re
import subprocess
import threading
import time
import urllib.parse
import urllib.request
import requests
from run import SCRATCH, RESULTS, probe, write

PORT = 8899
BASE = f"http://127.0.0.1:{PORT}"
FIXTURES = SCRATCH / "playback-fixtures"
URLS = {
    "ts": "https://devstreaming-cdn.apple.com/videos/streaming/examples/img_bipbop_adv_example_ts/master.m3u8",
    "fmp4": "https://devstreaming-cdn.apple.com/videos/streaming/examples/img_bipbop_adv_example_fmp4/master.m3u8",
    "ll": "https://demo.gvideo.io/cmaf/2675_19146/master.m3u8",
    "fairplay": "https://demo.cf.castlabs.com/media/fps/index.m3u8",
    "tracks": "https://storage.googleapis.com/shaka-demo-assets/angel-one-hls/hls.m3u8",
}
LOCK = threading.Lock()
RECOVERY = set()

def fetch(url, headers=None):
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers or {}), timeout=30) as response:
        return response.status, dict(response.headers), response.read()

def drm_fetch(url, headers=None, data=None):
    # urllib's single timeout also controls each DNS address connection attempt.
    # Bound connection fallback separately from reading the DRM response.
    started = time.monotonic()
    with requests.request("POST" if data is not None else "GET", url,
                          headers=headers, data=data, timeout=(3, 30)) as response:
        response.raise_for_status()
        body = response.content
        with LOCK:
            with (RESULTS / "playback-drm.jsonl").open("a") as file:
                file.write(json.dumps({"role": "drm-transport", "method": response.request.method,
                                       "status": response.status_code, "elapsed": time.monotonic() - started,
                                       "connectTimeout": 3, "readTimeout": 30}) + "\n")
        return response.status_code, dict(response.headers), body

def prepare():
    FIXTURES.mkdir(parents=True, exist_ok=True)
    for kind, child in [
        ("ts", "https://devstreaming-cdn.apple.com/videos/streaming/examples/img_bipbop_adv_example_ts/v2/prog_index.m3u8"),
        ("fmp4", "https://devstreaming-cdn.apple.com/videos/streaming/examples/img_bipbop_adv_example_fmp4/v2/prog_index.m3u8"),
    ]:
        _, _, data = fetch(child)
        (FIXTURES / f"{kind}-source.m3u8").write_bytes(data)
        text = data.decode().replace("\r\n", "\n")
        segments = re.findall(r"#EXTINF:([^,\n]+),[^\n]*\n((?:#[^\n]*\n)*)([^#\n]+)", text)[:6]
        if len(segments) != 6:
            raise RuntimeError(f"Expected six media segments from {child}, got {len(segments)}")
        media = []
        next_offset = 0
        for i, (duration, tags, uri) in enumerate(segments):
            request_headers = {}
            byte_range = re.search(r"#EXT-X-BYTERANGE:(\d+)(?:@(\d+))?", tags)
            if byte_range:
                length = int(byte_range[1])
                offset = int(byte_range[2]) if byte_range[2] else next_offset
                request_headers["Range"] = f"bytes={offset}-{offset+length-1}"
                next_offset = offset + length
            status, _, data = fetch(urllib.parse.urljoin(child, uri), request_headers)
            if byte_range:
                if status == 200:
                    data = data[offset:offset+length]
                if len(data) != length:
                    raise RuntimeError("Unexpected byte-range length from Apple fixture")
            path = FIXTURES / f"{kind}-{i}.bin"
            path.write_bytes(data)
            media.append({"duration": duration, "file": path.name, "origin": urllib.parse.urljoin(child, uri)})
        write(FIXTURES / f"{kind}.json", media)
        if kind == "ts":
            key = bytes(range(16))
            (FIXTURES / "key.bin").write_bytes(key)
            text = "#EXTM3U\n#EXT-X-VERSION:3\n#EXT-X-TARGETDURATION:7\n#EXT-X-PLAYLIST-TYPE:VOD\n"
            for i, entry in enumerate(media):
                key = bytes((j + i) % 256 for j in range(16))
                subprocess.run(["openssl", "enc", "-aes-128-cbc", "-K", key.hex(), "-iv", f"{i:032x}",
                                "-in", str(FIXTURES / entry["file"]), "-out", str(FIXTURES / f"aes-{i}.ts")], check=True)
                # Rotate both key bytes and URI, and exercise explicit IVs.
                (FIXTURES / f"key-{i}.bin").write_bytes(key)
                text += f'#EXT-X-KEY:METHOD=AES-128,URI="key-{i}.bin",IV=0x{i:032x}\n#EXTINF:{entry["duration"]},\naes-{i}.ts\n'
            (FIXTURES / "aes.m3u8").write_text(text + "#EXT-X-ENDLIST\n")
        else:
            init_tag = re.search(r"#EXT-X-MAP:([^\n]+)", text)[1]
            init = re.search(r'URI="([^"]+)"', init_tag)[1]
            init_range = re.search(r'BYTERANGE="(\d+)@(\d+)"', init_tag)
            init_headers = {}
            if init_range:
                length, offset = int(init_range[1]), int(init_range[2])
                init_headers["Range"] = f"bytes={offset}-{offset+length-1}"
            status, _, init_data = fetch(urllib.parse.urljoin(child, init), init_headers)
            if init_range:
                if status == 200:
                    init_data = init_data[offset:offset+length]
                if len(init_data) != length:
                    raise RuntimeError("Unexpected init byte-range length")
            data = bytearray(init_data)
            text = f'#EXTM3U\n#EXT-X-VERSION:7\n#EXT-X-TARGETDURATION:7\n#EXT-X-PLAYLIST-TYPE:VOD\n#EXT-X-MAP:URI="range.mp4",BYTERANGE="{len(data)}@0"\n'
            for entry in media:
                segment = (FIXTURES / entry["file"]).read_bytes()
                text += f'#EXTINF:{entry["duration"]},\n#EXT-X-BYTERANGE:{len(segment)}@{len(data)}\nrange.mp4\n'
                data.extend(segment)
            (FIXTURES / "range.mp4").write_bytes(data)
            (FIXTURES / "range.m3u8").write_text(text + "#EXT-X-ENDLIST\n")

class Handler(http.server.BaseHTTPRequestHandler):
    def log_message(self, *_):
        pass

    def do_HEAD(self):
        self.serve(False)

    def do_GET(self):
        self.serve(True)

    def do_POST(self):
        if self.path == "/done":
            data = self.rfile.read(int(self.headers["Content-Length"]))
            report = json.loads(data)
            target = "avplayer-simulator" if report.get("simulator") else "avplayer-device"
            run = report.get("run", "main")
            if run != "main":
                target += "-" + re.sub(r"[^a-zA-Z0-9-]", "", run)
            target += ".json"
            (RESULTS / target).write_bytes(data)
            self.send_response(200)
            self.end_headers()
        elif self.path == "/trace":
            data = self.rfile.read(int(self.headers["Content-Length"]))
            event = json.loads(data)
            with LOCK:
                with (RESULTS / "fairplay-trace.jsonl").open("a") as file:
                    file.write(json.dumps({**event, "serverTime": time.time()}) + "\n")
            self.send_response(200)
            self.end_headers()
        elif self.path == "/drm/license":
            data = self.rfile.read(int(self.headers["Content-Length"]))
            try:
                status, _, body = drm_fetch(
                    "https://lic.staging.drmtoday.com/license-server-fairplay/", data=data,
                    headers={"Content-Type": "application/x-www-form-urlencoded",
                             "x-dt-custom-data": self.headers["x-dt-custom-data"]})
                with LOCK:
                    with (RESULTS / "playback-drm.jsonl").open("a") as file:
                        file.write(json.dumps({"role": "license", "status": status,
                                               "requestBytes": len(data), "responseBytes": len(body)}) + "\n")
                self.send_response(status)
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)
            except Exception as error:
                with LOCK:
                    with (RESULTS / "playback-drm.jsonl").open("a") as file:
                        file.write(json.dumps({"role": "license", "status": getattr(getattr(error, "response", None), "status_code", None) or getattr(error, "code", 0),
                                               "error": str(error), "requestBytes": len(data)}) + "\n")
                self.send_error(502, str(error))
        else:
            self.send_error(404)

    def serve(self, body):
        status = 200
        headers = {}
        source = self.path
        try:
            path = urllib.parse.urlsplit(self.path)
            query = urllib.parse.parse_qs(path.query)
            if path.path == "/drm/cert":
                source = "https://lic.staging.drmtoday.com/license-server-fairplay/cert/"
                candidate = "certificate"
            elif path.path.startswith(("/raw/", "/render/")):
                _, mode, scheme, remainder = path.path.split("/", 3)
                source = scheme + "://" + remainder + ("?" + path.query if path.query else "")
                candidate = "raw" if mode == "raw" else "render-relative"
            elif path.path == "/resource":
                source = query["url"][0]
                candidate = query["candidate"][0]
                reload = [(key, value) for key in ["_HLS_msn", "_HLS_part", "_HLS_skip"] for value in query.get(key, [])]
                if reload:
                    source += ("&" if "?" in source else "?") + urllib.parse.urlencode(reload)
            elif path.path.startswith("/start/"):
                _, _, kind, candidate = path.path.split("/")
                source = URLS[kind] if kind in URLS else BASE + "/fixture/" + {
                    "aes": "aes.m3u8", "range": "range.m3u8",
                    "live": "live.m3u8", "recovery": "aes.m3u8",
                }[kind]
            elif path.path.startswith("/fixture/"):
                candidate = "original"
                source = BASE + self.path
            else:
                self.send_error(404)
                return
            if source.startswith(BASE + "/fixture/"):
                filename = urllib.parse.urlsplit(source).path.removeprefix("/fixture/")
                if filename == "live.m3u8":
                    entries = json.loads((FIXTURES / "ts.json").read_text())
                    sequence = int(time.time() // 6)
                    text = f"#EXTM3U\n#EXT-X-VERSION:3\n#EXT-X-TARGETDURATION:7\n#EXT-X-MEDIA-SEQUENCE:{sequence}\n"
                    for i in range(sequence, sequence + 4):
                        entry = entries[i % len(entries)]
                        text += f'#EXT-X-DISCONTINUITY\n#EXTINF:{entry["duration"]},\n{entry["file"]}\n'
                    data = text.encode()
                else:
                    data = (FIXTURES / filename).read_bytes()
                if self.headers.get("Range") and not filename.endswith(".m3u8"):
                    match = re.fullmatch(r"bytes=(\d+)-(\d*)", self.headers["Range"])
                    start = int(match[1])
                    end = int(match[2]) if match[2] else len(data) - 1
                    end = min(end, len(data) - 1)
                    headers["Content-Range"] = f"bytes {start}-{end}/{len(data)}"
                    data = data[start:end + 1]
                    status = 206
                headers["Accept-Ranges"] = "bytes"
            else:
                request_headers = {"Range": self.headers["Range"]} if self.headers.get("Range") else {}
                if candidate == "certificate":
                    certificate_started = time.time()
                    with LOCK:
                        with (RESULTS / "playback-drm.jsonl").open("a") as file:
                            file.write(json.dumps({"role": "certificate-fetch-start", "time": certificate_started}) + "\n")
                    request_headers["x-dt-custom-data"] = base64.b64encode(
                        json.dumps({"merchant": "six", "userId": "purchase", "sessionId": "session"},
                                   separators=(",", ":")).encode()).decode()
                status, headers, data = (drm_fetch(source, request_headers) if candidate == "certificate"
                                         else fetch(source, request_headers))
                if candidate == "certificate":
                    with LOCK:
                        with (RESULTS / "playback-drm.jsonl").open("a") as file:
                            file.write(json.dumps({"role": "certificate-fetched", "time": time.time(),
                                                   "elapsed": time.time() - certificate_started, "status": status}) + "\n")
            if data.startswith(b"#EXTM3U"):
                text = data.decode()
                if candidate == "render-relative":
                    row = probe([{"name": source, "text": text, "url": source}])[0]
                    if row["status"] != "accepted":
                        with LOCK:
                            with (RESULTS / "playback-rejections.jsonl").open("a") as file:
                                file.write(json.dumps({"source": source, "candidate": candidate, "status": 422, "error": row["error"]}) + "\n")
                        self.send_error(422)
                        return
                    text = row["text"]
                elif candidate not in ["original", "raw"]:
                    row = probe([{"name": source, "text": text, "url": source,
                                  "rewrite": candidate != "render", "resolve": candidate == "render",
                                  "proxy": BASE + "/resource&candidate=" + candidate}])[0]
                    if row["status"] != "accepted":
                        with LOCK:
                            with (RESULTS / "playback-rejections.jsonl").open("a") as file:
                                file.write(json.dumps({"source": source, "candidate": candidate, "status": 422, "error": row["error"]}) + "\n")
                        self.send_error(422)
                        return
                    # Probe appends ?url=. Use normal query separators in this test server.
                    text = row["text"].replace("/resource&candidate=" + candidate + "?url=",
                                               "/resource?candidate=" + candidate + "&url=")
                    with LOCK:
                        with (RESULTS / "playback-manifests.jsonl").open("a") as file:
                            file.write(json.dumps({"source": source, "candidate": candidate, "original": data.decode(),
                                                   "output": text, "roles": row["roles"]}) + "\n")
                data = text.encode()
                headers["Content-Type"] = "application/vnd.apple.mpegurl"
            elif candidate == "certificate":
                delay = min(45, max(0, int(query.get("delay", ["0"])[0])))
                if delay:
                    with LOCK:
                        with (RESULTS / "playback-drm.jsonl").open("a") as file:
                            file.write(json.dumps({"role": "certificate-controlled-delay", "seconds": delay, "time": time.time()}) + "\n")
                    time.sleep(delay)
                with LOCK:
                    with (RESULTS / "playback-drm.jsonl").open("a") as file:
                        file.write(json.dumps({"role": "certificate", "status": status,
                                               "responseBytes": len(data)}) + "\n")
            elif candidate == "recovery" and source.endswith(".ts"):
                with LOCK:
                    if "segment" not in RECOVERY:
                        RECOVERY.add("segment")
                        status, data = 503, b"controlled transient failure"
            with LOCK:
                with (RESULTS / "playback-requests.jsonl").open("a") as file:
                    file.write(json.dumps({"time": time.time(), "source": source, "candidate": candidate,
                                           "status": status, "range": self.headers.get("Range"), "bytes": len(data)}) + "\n")
            self.send_response(status)
            for key in ["Content-Type", "Content-Range", "Accept-Ranges"]:
                if headers.get(key):
                    self.send_header(key, headers[key])
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            if body:
                self.wfile.write(data)
        except (BrokenPipeError, ConnectionResetError):
            pass
        except Exception as error:
            with LOCK:
                with (RESULTS / "playback-server-errors.log").open("a") as file:
                    file.write(f"{source}: {error}\n")
            self.send_error(502)

if __name__ == "__main__":
    import sys
    if "--prepare" in sys.argv:
        prepare()
    else:
        RESULTS.mkdir(parents=True, exist_ok=True)
        http.server.ThreadingHTTPServer(("127.0.0.1", PORT), Handler).serve_forever()
